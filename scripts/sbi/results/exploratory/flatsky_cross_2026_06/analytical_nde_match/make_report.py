    W("    --out TABLE1_ERRORBARS_FULL.json --md TABLE1_ERRORBARS_FULL.md")
    W("```")
    W("")
    W("**Preprocessing differs by arm type and this matters.** The compression stage uses")
    W("`log1p-zscore / clip 5 / min-var 1e-5`. The downstream sweep on the 10-D summaries uses")
    W("`none / clip 0 / min-var 1e-12` for **both** ℓ1 and CNN arms — the campaign's own")
