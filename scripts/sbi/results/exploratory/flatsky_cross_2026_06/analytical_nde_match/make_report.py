    W("    --out-cache <raw>/cache --out-fid <raw>/fid.npz")
    W("")
    W("# 2. VMIM compressor, one per seed")
    W("vmim_from_cache.py --cache-dir <raw>/cache --fid-npz <raw>/fid.npz \\")
    W("    --out-cache <arm> --out-fid <arm>/fiducial_summaries.npz \\")
    W("    --summary-dim 10 --hidden 256,256 --nf-layers 4 --nf-hidden 128 \\")
    W("    --steps 30000 --seed <41|42|43> \\")
    W("    --preproc-transform log1p-zscore --clip-value 5 --min-feature-variance 1e-5")
